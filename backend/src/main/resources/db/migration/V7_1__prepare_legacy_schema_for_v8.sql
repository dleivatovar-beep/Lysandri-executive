-- Forward-only compatibility step: protect V8 from the V1 legacy ORDERS shape.
-- This migration runs only for new databases prior to V8; previously recorded V8 databases use V23.
DO $$
DECLARE
    constraint_row RECORD;
BEGIN
    -- Keep the original catalog fields available for explicit modern-field mapping in V23.
    -- V8 now retains instructors and academic records.
     IF to_regclass('public.ordenes') IS NOT NULL
         AND to_regclass('public.programa') IS NOT NULL
         AND EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='programa' AND column_name='titulo_programa')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='programa' AND column_name='titulo') THEN
        IF to_regclass('public.lysandri_v7_programa_backup') IS NULL THEN
            CREATE TABLE lysandri_v7_programa_backup AS TABLE programa;
        END IF;
    END IF;

    -- Remove only foreign keys on these legacy tables while their referenced key types are normalized.
    IF to_regclass('public.ordenes') IS NULL THEN
        RETURN;
    END IF;
    FOR constraint_row IN
        SELECT conname FROM pg_constraint
        WHERE conrelid = 'public.ordenes'::regclass AND contype = 'f'
    LOOP
        EXECUTE format('ALTER TABLE public.ordenes DROP CONSTRAINT %I', constraint_row.conname);
    END LOOP;

    IF to_regclass('public.detalle_ordenes') IS NOT NULL THEN
        FOR constraint_row IN
            SELECT conname FROM pg_constraint
            WHERE conrelid = 'public.detalle_ordenes'::regclass AND contype = 'f'
        LOOP
            EXECUTE format('ALTER TABLE public.detalle_ordenes DROP CONSTRAINT %I', constraint_row.conname);
        END LOOP;
    END IF;

    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='ordenes' AND column_name='id_ordenes')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='ordenes' AND column_name='id_orden') THEN
        ALTER TABLE ordenes RENAME COLUMN id_ordenes TO id_orden;
    END IF;
    IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='ordenes' AND column_name='estado_order')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='ordenes' AND column_name='estado_orden') THEN
        ALTER TABLE ordenes RENAME COLUMN estado_order TO estado_orden;
    END IF;

    ALTER TABLE ordenes ADD COLUMN IF NOT EXISTS codigo_orden VARCHAR(36);
    ALTER TABLE ordenes ADD COLUMN IF NOT EXISTS moneda VARCHAR(3) DEFAULT 'USD';
    ALTER TABLE ordenes ADD COLUMN IF NOT EXISTS stripe_session_id VARCHAR(255);
    ALTER TABLE ordenes ADD COLUMN IF NOT EXISTS stripe_payment_intent_id VARCHAR(255);
    ALTER TABLE ordenes ADD COLUMN IF NOT EXISTS moodle_matricula_sincronizada BOOLEAN DEFAULT FALSE;
    ALTER TABLE ordenes ADD COLUMN IF NOT EXISTS fecha_pago TIMESTAMPTZ;
    UPDATE ordenes SET codigo_orden = 'LEGACY-' || id_orden WHERE codigo_orden IS NULL;
    UPDATE ordenes SET moneda = 'USD' WHERE moneda IS NULL OR BTRIM(moneda) = '';
    UPDATE ordenes SET moodle_matricula_sincronizada = FALSE WHERE moodle_matricula_sincronizada IS NULL;
    ALTER TABLE ordenes ALTER COLUMN codigo_orden SET NOT NULL;
    ALTER TABLE ordenes ALTER COLUMN id_orden TYPE BIGINT;
    IF (SELECT is_identity FROM information_schema.columns WHERE table_schema='public' AND table_name='ordenes' AND column_name='id_orden') = 'NO' THEN
        ALTER TABLE ordenes ALTER COLUMN id_orden DROP DEFAULT;
        ALTER TABLE ordenes ALTER COLUMN id_orden ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
    ALTER TABLE ordenes ALTER COLUMN id_user TYPE BIGINT;
    PERFORM setval(pg_get_serial_sequence('ordenes', 'id_orden'),
                   GREATEST(COALESCE((SELECT MAX(id_orden) FROM ordenes), 1), 1),
                   EXISTS (SELECT 1 FROM ordenes));
    CREATE UNIQUE INDEX IF NOT EXISTS uq_ordenes_codigo_orden ON ordenes(codigo_orden);

    IF to_regclass('public.detalle_ordenes') IS NOT NULL THEN
        IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='detalle_ordenes' AND column_name='id_detalle_ordenes')
           AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='detalle_ordenes' AND column_name='id_detalle') THEN
            ALTER TABLE detalle_ordenes RENAME COLUMN id_detalle_ordenes TO id_detalle;
        END IF;
        IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='detalle_ordenes' AND column_name='id_ordenes')
           AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='detalle_ordenes' AND column_name='id_orden') THEN
            ALTER TABLE detalle_ordenes RENAME COLUMN id_ordenes TO id_orden;
        END IF;
        ALTER TABLE detalle_ordenes ADD COLUMN IF NOT EXISTS moodle_matriculado BOOLEAN DEFAULT FALSE;
        UPDATE detalle_ordenes SET moodle_matriculado = FALSE WHERE moodle_matriculado IS NULL;
        ALTER TABLE detalle_ordenes ALTER COLUMN moodle_matriculado SET DEFAULT FALSE;
        ALTER TABLE detalle_ordenes ALTER COLUMN moodle_matriculado SET NOT NULL;
        ALTER TABLE detalle_ordenes ALTER COLUMN id_detalle TYPE BIGINT;
        IF (SELECT is_identity FROM information_schema.columns WHERE table_schema='public' AND table_name='detalle_ordenes' AND column_name='id_detalle') = 'NO' THEN
            ALTER TABLE detalle_ordenes ALTER COLUMN id_detalle DROP DEFAULT;
            ALTER TABLE detalle_ordenes ALTER COLUMN id_detalle ADD GENERATED BY DEFAULT AS IDENTITY;
        END IF;
        ALTER TABLE detalle_ordenes ALTER COLUMN id_orden TYPE BIGINT;
        ALTER TABLE detalle_ordenes ALTER COLUMN id_programa TYPE BIGINT;
        PERFORM setval(pg_get_serial_sequence('detalle_ordenes', 'id_detalle'),
                       GREATEST(COALESCE((SELECT MAX(id_detalle) FROM detalle_ordenes), 1), 1),
                       EXISTS (SELECT 1 FROM detalle_ordenes));
    END IF;
END $$;
